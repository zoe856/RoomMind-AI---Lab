from scipy.optimize import linear_sum_assignment

def compare_rooms(before_objects, after_objects,
                  move_threshold=0.08,
                  match_threshold=0.35):

    changes = []
    classes = sorted(set(
        obj["object"] for obj in before_objects + after_objects
    ))

    for object_name in classes:
        before_group = [
            obj for obj in before_objects
            if obj["object"] == object_name
        ]

        after_group = [
            obj for obj in after_objects
            if obj["object"] == object_name
        ]

        matched_before = set()
        matched_after = set()

        if before_group and after_group:
            # Compare normalized object centers
            before_centers = np.array([
                [obj["center_x"], obj["center_y"]]
                for obj in before_group
            ])

            after_centers = np.array([
                [obj["center_x"], obj["center_y"]]
                for obj in after_group
            ])

            distances = np.linalg.norm(
                before_centers[:, None, :] -
                after_centers[None, :, :],
                axis=2
            )

            rows, cols = linear_sum_assignment(distances)

            for i, j in zip(rows, cols):
                distance = float(distances[i, j])

                if distance > match_threshold:
                    continue

                matched_before.add(i)
                matched_after.add(j)

                if distance > move_threshold:
                    status = "Potentially moved"
                else:
                    status = "No major position change"

                changes.append({
                    "Object": object_name,
                    "Status": status,
                    "Position Shift": round(distance, 3),
                    "Before Confidence": before_group[i]["confidence"],
                    "After Confidence": after_group[j]["confidence"]
                })

        for i, obj in enumerate(before_group):
            if i not in matched_before:
                changes.append({
                    "Object": object_name,
                    "Status": "Potentially removed",
                    "Position Shift": None,
                    "Before Confidence": obj["confidence"],
                    "After Confidence": None
                })

        for j, obj in enumerate(after_group):
            if j not in matched_after:
                changes.append({
                    "Object": object_name,
                    "Status": "Potentially added",
                    "Position Shift": None,
                    "Before Confidence": None,
                    "After Confidence": obj["confidence"]
                })

    return pd.DataFrame(changes)


