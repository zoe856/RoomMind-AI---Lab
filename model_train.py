class RoomPairDataset(Dataset):
    def __init__(self, before_dir, after_dir, mask_dir, image_size=256):
        self.before_dir = Path(before_dir)
        self.after_dir = Path(after_dir)
        self.mask_dir = Path(mask_dir)
        self.image_size = image_size

        extensions = {".jpg", ".jpeg", ".png", ".bmp"}

        self.names = sorted(
            p.name for p in self.before_dir.iterdir()
            if p.suffix.lower() in extensions
            and (self.after_dir / p.name).exists()
            and (self.mask_dir / p.name).exists()
        )

        if not self.names:
            raise ValueError(
                "No matching before, after, and mask files found."
            )

    def __len__(self):
        return len(self.names)

    def __getitem__(self, idx):
        name = self.names[idx]

        before = Image.open(
            self.before_dir / name
        ).convert("RGB").resize(
            (self.image_size, self.image_size)
        )

        after = Image.open(
            self.after_dir / name
        ).convert("RGB").resize(
            (self.image_size, self.image_size)
        )

        mask = Image.open(
            self.mask_dir / name
        ).convert("L").resize(
            (self.image_size, self.image_size)
        )

        before = np.asarray(before, dtype=np.float32) / 255.0
        after = np.asarray(after, dtype=np.float32) / 255.0
        mask = np.asarray(mask, dtype=np.float32) / 255.0

        before = torch.from_numpy(before).permute(2, 0, 1)
        after = torch.from_numpy(after).permute(2, 0, 1)
        mask = torch.from_numpy(mask).unsqueeze(0)

        mask = (mask > 0.5).float()

        return before, after, mask

class ConvBlock(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()

        self.block = nn.Sequential(
            nn.Conv2d(
                in_channels, out_channels,
                kernel_size=3, padding=1
            ),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),

            nn.Conv2d(
                out_channels, out_channels,
                kernel_size=3, padding=1
            ),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.block(x)


class SharedEncoder(nn.Module):
    def __init__(self):
        super().__init__()

        self.block1 = ConvBlock(3, 32)
        self.block2 = ConvBlock(32, 64)
        self.block3 = ConvBlock(64, 128)
        self.block4 = ConvBlock(128, 256)
        self.pool = nn.MaxPool2d(2)

    def forward(self, x):
        x = self.block1(x)
        x = self.pool(x)

        x = self.block2(x)
        x = self.pool(x)

        x = self.block3(x)
        x = self.pool(x)

        x = self.block4(x)
        return x


class RoomMindNet(nn.Module):
    def __init__(self):
        super().__init__()

        self.encoder = SharedEncoder()

        self.decoder = nn.Sequential(
            ConvBlock(256 * 3, 256),
            nn.ConvTranspose2d(
                256, 128, kernel_size=2, stride=2
            ),
            ConvBlock(128, 128),

            nn.ConvTranspose2d(
                128, 64, kernel_size=2, stride=2
            ),
            ConvBlock(64, 64),

            nn.ConvTranspose2d(
                64, 32, kernel_size=2, stride=2
            ),
            ConvBlock(32, 32),

            nn.Conv2d(32, 1, kernel_size=1)
        )

    def forward(self, before, after):
        f_before = self.encoder(before)
        f_after = self.encoder(after)

        combined = torch.cat(
            [
                f_before,
                f_after,
                torch.abs(f_before - f_after)
            ],
            dim=1
        )

        return self.decoder(combined)


